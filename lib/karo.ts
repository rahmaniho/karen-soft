export type KaroPlanId = (typeof KARO_PLANS)[number]["id"];
export function calculateKaroSubscription(
  planId: KaroPlanId,
  users: number,
  months: number,
): number {
  const plan = KARO_PLANS.find((item) => item.id === planId);
  if (
    !plan ||
    !Number.isSafeInteger(users) ||
    users < 1 ||
    !Number.isSafeInteger(months) ||
    months < 1
  )
    throw new RangeError("پلن، تعداد کاربران و مدت اشتراک معتبر نیست.");
  const total = (plan.price + (users - 1) * plan.extraUserMonthly) * months;
  if (!Number.isSafeInteger(total))
    throw new RangeError("مبلغ خارج از محدوده مجاز است.");
  return total;
}
