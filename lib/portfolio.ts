/**
 * نوع نمونه‌کار:
 * - client: پروژهٔ واقعی یک مشتری، همراه با نتیجه‌های ثبت‌شده.
 * - sample: نمونهٔ عمومی یا نسخهٔ نمایشی یک پروژه؛ بدون ادعای نتیجهٔ اندازه‌گیری‌شده.
 * - hypothetical: سناریوی فرضی با نام و داده‌های ساختگی؛ همیشه با یادداشت شفافیت.
 */
export type CaseKind = "client" | "sample" | "hypothetical";

/** نسخهٔ نمایشی داخل سایت؛ همیشه هم‌مبدأ است و هیچ پیوند بیرونی ندارد. */
export interface CaseStudyDemo {
  /** مسیر نقطهٔ ورود نسخهٔ نمایشی (برای دموهای ایستا در public/demos/<slug>). */
  src: string;
  /** پیوندها و فرم‌ها فقط داخل این مسیر مجازند؛ بقیه در نسخهٔ نمایشی غیرفعال می‌شوند. */
  scope: string;
  /** عنوان قابل‌دسترس برای iframe. */
  title: string;
  /** اگر تعریف شود، پیوند «صفحهٔ کامل» داخل همین سایت نمایش داده می‌شود. */
  fullPageHref?: string;
}

/** یک ردیف مشخصهٔ فنی یا ویژگی سایت؛ در صفحهٔ نمونه‌کار در قالب شبکه نمایش داده می‌شود. */
export interface CaseStudySpec {
  label: string;
  value: string;
}

/** نظر مشتری؛ عکس و لوگوی گوینده اختیاری است. */
export interface CaseStudyQuote {
  text: string;
  author: string;
  role?: string;
  /** مسیر عکس گوینده (نسبت ۳:۴ یا ۴:۵ بهتر است). */
  avatar?: string;
  /** مسیر لوگوی شرکت گوینده. */
  logo?: string;
}

export interface CaseStudy {
  slug: string;
  kind: CaseKind;
  title: string;
  client: string;
  category: string;
  year: string;
  summary: string;
  cover: string;
  accent: string;
  /** لوگوی مشتری یا محصول؛ روی کارت و بالای صفحهٔ نمونه‌کار نمایش داده می‌شود. */
  logo?: string;
  /** نشانی وب‌سایت واقعی مشتری؛ برای مطالعهٔ بیشتر و با rel امن. */
  liveUrl?: string;
  /** مشخصات کوتاه سایت یا محصول. */
  specs?: CaseStudySpec[];
  /** تصویرسازی اختصاصی که بالای نسخهٔ نمایشی رندر می‌شود. */
  visual?: "smart-factory";
  /** یادداشت شفافیت که بالای نسخهٔ نمایشی یا صفحه نشان داده می‌شود. */
  note?: string;
  demo?: CaseStudyDemo;
  /**
   * چند نسخهٔ نمایشی از یک پروژه؛ مثلاً فروشگاه و پنل مدیریت آن.
   * اگر تعریف شود، در صفحهٔ نمونه‌کار با تب جابه‌جا می‌شوند.
   */
  demoVariants?: { label: string; demo: CaseStudyDemo }[];
  services: string[];
  challenge: string[];
  solution: string[];
  results?: { value: string; label: string }[];
  stack: string[];
  quote?: CaseStudyQuote;
}

